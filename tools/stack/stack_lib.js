const glyphRows = () => Object.entries(G).map(([ch, rows]) => [ch.codePointAt(0), rows.join("")]);

// Static bitmap lettering rendered at build time (for fixed titles).
function pixelRects(text, x, y, p) {
  let out = "";
  [...text].forEach((ch, i) => {
    const rows = G[ch] || G[" "];
    rows.forEach((row, r) => {
      [...row].forEach((bit, c) => {
        if (bit === "1") out += `<rect x='${x + i * 6 * p + c * p}' y='${y + r * p}' width='${p}' height='${p}'/>`;
      });
    });
  });
  return out;
}
const pixelWidth = (text, p) => text.length * 6 * p - p;

// DAX expression that renders dynamic bitmap text via the Glyphs table.
// textDax, xDax, yDax are DAX expressions; p is an integer pixel size; id keeps VAR names unique.
function daxPixel(textDax, xDax, yDax, p, id) {
  const t = `_pt${id}`, x = `_px${id}`, y = `_py${id}`;
  return `(
        VAR ${t} = ${textDax}
        VAR ${x} = ${xDax}
        VAR ${y} = ${yDax}
        RETURN
            CONCATENATEX(
                GENERATE(
                    SELECTCOLUMNS(GENERATESERIES(1, LEN(${t}), 1), "ci${id}", [Value]),
                    VAR _bits = LOOKUPVALUE('Glyphs'[Bits], 'Glyphs'[Code], UNICODE(MID(${t}, [ci${id}], 1)), REPT("0", 35))
                    RETURN FILTER(SELECTCOLUMNS(GENERATESERIES(0, 34, 1), "cell${id}", [Value]), MID(_bits, [cell${id}] + 1, 1) = "1")
                ),
                "<rect x='" & (${x} + ([ci${id}] - 1) * ${6 * p} + MOD([cell${id}], 5) * ${p}) & "' y='" & (${y} + INT([cell${id}] / 5) * ${p}) & "' width='${p}' height='${p}'/>",
                ""
            )
    )`;
}

